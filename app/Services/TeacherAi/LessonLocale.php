    private function __construct() {}

    /**
     * Known language code for any input; unknown or empty → Russian.
     */
    public static function normalize(string $code): string
    {
        $code = strtolower(trim($code));

        return isset(self::LANGUAGES[$code]) ? $code : self::DEFAULT;
    }

    public static function label(string $code): string
    {
        return self::LANGUAGES[self::normalize($code)];
    }

    /**
     * Word for the «Пиши на … языке» instruction of the system prompt.
     */
    public static function promptLanguage(string $code): string
    {
        return self::PROMPT_LANGUAGES[self::normalize($code)];
    }

    /**
     * @return list<array{value: string, label: string}>
     */
    public static function options(): array
    {
        $options = [];

        foreach (self::LANGUAGES as $value => $label) {
            $options[] = ['value' => $value, 'label' => $label];
        }

        return $options;
    }

    /**
     * @return array<string, string>
     */
    public static function labels(string $code): array
    {
        return self::LABELS[self::normalize($code)];
    }

    /**
     * Lecture title as written on the title slide: «7-Дәріс. …», «Лекция 7. …», «Lecture 7. …».
     */
    public static function lectureTitle(string $code, ?int $number, string $title): string
    {
        if ($number === null || $number < 1) {
            return $title;
        }

        return sprintf(self::labels($code)['lecture_number'], $number).$title;
    }
