const STRUCTURAL_UNIT_LABELS = {
    'ВиСР': 'ВиСР — Воспитательная и социальная работа',
    'ОМОиАМ': 'ОМОиАМ — Отдел международного образования и академической мобильности (ОМОиАМ)',
    'ОР': 'ОР — Офис регистратора',
    'ОРиА': 'ОРиА — Отдел рейтингов и аккредитации',
    'ОУП': 'ОУП — Отдел управления персоналом',
    'УМиФК': 'УМиФК — Управление маркетинга и формирование контингента',
    'УНиВС': 'УНиВС — Управление науки и внешних связей (УНиВС)',
    'УОКиА': 'УОКиА — Управление обеспечения качества и аккредитации',
    'УОП': 'УОП — Управление образовательных программ',
    'ЦК': 'ЦК — Центр компетенции',
    'ЦКАР': 'ЦКАР — Центр карьеры',
    'ЭФ': 'ЭФ — Эндаумент фонд',
};

export function formatStructuralUnitLabel(unit) {
    if (!unit) {
        return '—';
    }

    const code = String(unit.code ?? '').trim();
    if (code && STRUCTURAL_UNIT_LABELS[code]) {
        return STRUCTURAL_UNIT_LABELS[code];
    }

    const name = String(unit.name ?? '').trim();

    if (code && name) {
        return `${code} — ${name}`;
    }

    return code || name || '—';
}